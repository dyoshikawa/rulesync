import { dirname, join } from "node:path";

import { describe, expect, it } from "vitest";

import { RULESYNC_CONFIG_RELATIVE_FILE_PATH } from "../constants/rulesync-paths.js";
import { fileExists, readFileContent, writeFileContent } from "../utils/file.js";
import { execFileAsync, rulesyncArgs, rulesyncCmd, useTestDirectory } from "./e2e-helper.js";

describe("E2E: gitignore command", () => {
  const { getTestDir } = useTestDirectory();

  it("should write target entries to .gitattributes when tool-level destination is configured", async () => {
    const testDir = getTestDir();

    await writeFileContent(
      join(testDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
      `{
  "targets": {
    "claudecode": {
      "gitignoreDestination": "gitattributes",
      "rules": true
    }
  }
}
`,
    );

    await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"]);

    const gitignoreContent = await readFileContent(join(testDir, ".gitignore"));
    const gitattributesContent = await readFileContent(join(testDir, ".gitattributes"));

    expect(gitignoreContent).toContain(".rulesync/skills/.curated/");
    expect(gitignoreContent).not.toContain("**/CLAUDE.md");
    expect(gitattributesContent).toContain("**/CLAUDE.md");
  });

  it("should write entries to .gitattributes when root-level destination is configured", async () => {
    const testDir = getTestDir();

    await writeFileContent(
      join(testDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
      `{
  "gitignoreDestination": "gitattributes",
  "targets": {
    "claudecode": ["rules"]
  }
}
`,
    );

    await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"]);

    const gitignoreContent = await readFileContent(join(testDir, ".gitignore"));
    const gitattributesContent = await readFileContent(join(testDir, ".gitattributes"));

    expect(gitignoreContent).not.toContain("**/CLAUDE.md");
    expect(gitattributesContent).toContain("**/CLAUDE.md");
  });

  it("should prefer tool x feature destination over tool-level destination", async () => {
    const testDir = getTestDir();

    await writeFileContent(
      join(testDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
      `{
  "targets": {
    "claudecode": {
      "gitignoreDestination": "gitattributes",
      "rules": { "gitignoreDestination": "gitignore" }
    }
  }
}
`,
    );

    await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"]);

    const gitignoreContent = await readFileContent(join(testDir, ".gitignore"));
    const gitattributesContent = await readFileContent(join(testDir, ".gitattributes"));

    expect(gitignoreContent).toContain("**/CLAUDE.md");
    expect(gitattributesContent).not.toContain("**/CLAUDE.md");
  });
  describe("gitexclude destination", () => {
    // Keep git from walking up into the repository that hosts the test
    // directory, so each test sees only the repository it creates.
    const gitEnv = (testDir: string): NodeJS.ProcessEnv => ({
      ...process.env,
      GIT_CEILING_DIRECTORIES: dirname(testDir),
    });

    const git = async (args: string[], { cwd, env }: { cwd: string; env: NodeJS.ProcessEnv }) =>
      execFileAsync(
        "git",
        ["-c", "user.name=rulesync", "-c", "user.email=rulesync@example.com", ...args],
        { cwd, env },
      );

    it("should write entries to .git/info/exclude when set from rulesync.local.jsonc", async () => {
      const testDir = getTestDir();
      const env = gitEnv(testDir);
      await git(["init", "-q"], { cwd: testDir, env });
      await writeFileContent(
        join(testDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
        `{ "targets": { "claudecode": ["rules"] } }\n`,
      );
      await writeFileContent(
        join(testDir, "rulesync.local.jsonc"),
        `{ "gitignoreDestination": "gitexclude" }\n`,
      );

      await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], { env });
      const excludePath = join(testDir, ".git", "info", "exclude");
      const firstContent = await readFileContent(excludePath);
      await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], { env });

      expect(firstContent).toContain("# Generated by Rulesync");
      expect(firstContent).toContain("**/CLAUDE.md");
      expect(firstContent).toContain("rulesync.local.jsonc");
      expect(firstContent).toContain("# End of Rulesync");
      expect(await readFileContent(excludePath)).toBe(firstContent);
      expect(await fileExists(join(testDir, ".gitignore"))).toBe(false);
      const { stdout } = await git(["check-ignore", "CLAUDE.md"], { cwd: testDir, env });
      expect(stdout.trim()).toBe("CLAUDE.md");
    });

    it("should keep hand-written exclude lines with and without gitexclude configured", async () => {
      const testDir = getTestDir();
      const env = gitEnv(testDir);
      await git(["init", "-q"], { cwd: testDir, env });
      const excludePath = join(testDir, ".git", "info", "exclude");
      const handWritten = "**/.agents/skills/\n**/.claude/settings.local.json\n";
      await writeFileContent(excludePath, handWritten);
      const configPath = join(testDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH);

      await writeFileContent(configPath, `{ "targets": { "claudecode": ["rules", "ignore"] } }\n`);
      await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], { env });
      expect(await readFileContent(excludePath)).toBe(handWritten);

      await writeFileContent(
        configPath,
        `{ "gitignoreDestination": "gitexclude", "targets": { "claudecode": ["rules", "ignore"] } }\n`,
      );
      await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], { env });
      const excludeContent = await readFileContent(excludePath);
      expect(excludeContent.startsWith(`${handWritten}\n# Generated by Rulesync\n`)).toBe(true);
      expect(excludeContent).toContain("**/CLAUDE.md");
    });

    it("should fail when run below the repository root", async () => {
      const testDir = getTestDir();
      const env = gitEnv(testDir);
      const projectDir = join(testDir, "packages", "app");
      await git(["init", "-q"], { cwd: testDir, env });
      await writeFileContent(
        join(projectDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
        `{ "gitignoreDestination": "gitexclude", "targets": { "claudecode": ["rules"] } }\n`,
      );

      await expect(
        execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], {
          cwd: projectDir,
          env: { ...env, NODE_ENV: "e2e" },
        }),
      ).rejects.toMatchObject({
        stderr: expect.stringContaining("must be used from the repository root"),
      });
      const excludePath = join(testDir, ".git", "info", "exclude");
      const excludeContent = (await fileExists(excludePath))
        ? await readFileContent(excludePath)
        : "";
      expect(excludeContent).not.toContain("Generated by Rulesync");
    });

    it("should write to the common exclude file from a linked worktree", async () => {
      const testDir = getTestDir();
      const env = gitEnv(testDir);
      const mainDir = join(testDir, "main");
      const worktreeDir = join(testDir, "linked");
      await writeFileContent(join(mainDir, "README.md"), "# test\n");
      await git(["init", "-q"], { cwd: mainDir, env });
      await git(["add", "README.md"], { cwd: mainDir, env });
      await git(["commit", "-q", "-m", "init"], { cwd: mainDir, env });
      await git(["worktree", "add", "-q", worktreeDir], { cwd: mainDir, env });
      await writeFileContent(
        join(worktreeDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
        `{ "gitignoreDestination": "gitexclude", "targets": { "claudecode": ["rules"] } }\n`,
      );

      await execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], { cwd: worktreeDir, env });

      const excludeContent = await readFileContent(join(mainDir, ".git", "info", "exclude"));
      expect(excludeContent).toContain("**/CLAUDE.md");
      expect(await fileExists(join(worktreeDir, ".gitignore"))).toBe(false);
    });

    it("should fail with a clear error outside a Git repository", async () => {
      const testDir = getTestDir();
      await writeFileContent(
        join(testDir, RULESYNC_CONFIG_RELATIVE_FILE_PATH),
        `{ "gitignoreDestination": "gitexclude", "targets": { "claudecode": ["rules"] } }\n`,
      );

      await expect(
        execFileAsync(rulesyncCmd, [...rulesyncArgs, "gitignore"], {
          env: { ...gitEnv(testDir), NODE_ENV: "e2e" },
        }),
      ).rejects.toMatchObject({
        stderr: expect.stringContaining(
          'gitignoreDestination "gitexclude" requires a Git repository',
        ),
      });
      expect(await fileExists(join(testDir, ".gitignore"))).toBe(false);
    });
  });
});
