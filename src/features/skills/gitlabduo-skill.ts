import { join } from "node:path";

import { SKILL_FILE_NAME } from "../../constants/general.js";
import {
  GITLABDUO_GLOBAL_SKILLS_DIR,
  GITLABDUO_LEGACY_SKILLS_DIR,
  GITLABDUO_SKILLS_DIR,
} from "../../constants/gitlabduo-paths.js";
import { fileExists } from "../../utils/file.js";
import { AgentsSkillsSkill } from "./agentsskills-skill.js";
import { RulesyncSkill } from "./rulesync-skill.js";
import { ToolSkillSettablePaths } from "./tool-skill.js";

/**
 * GitLab Duo skills follow the Agent Skills standard (`name` and `description`
 * are required; `metadata: { slash-command: enabled }` exposes a skill as a
 * slash command), so this target reuses {@link AgentsSkillsSkill} with GitLab's
 * locations:
 *
 * - Project skills are written to the cross-tool `.agents/skills/<name>/SKILL.md`
 *   root, which both the GitLab UI flows and the GitLab Duo CLI read. GitLab
 *   Duo also reads a non-hidden `skills/<name>/SKILL.md` at the project root
 *   (`.agents/skills/` wins on a name clash); rulesync imports from it but
 *   never writes or sweeps it, because that directory routinely holds
 *   hand-authored skills. Earlier rulesync versions wrote there, so a skill
 *   generated by one of them has to be removed from `skills/` by hand.
 * - User skills live in `~/.gitlab/duo/skills/` and are loaded by the CLI only
 *   when started with `--enable-global-skills true` (or
 *   `GITLAB_ENABLE_GLOBAL_SKILLS=true`).
 *
 * @see https://docs.gitlab.com/user/duo_agent_platform/customize/agent_skills/
 */
export class GitlabduoSkill extends AgentsSkillsSkill {
  static override getSettablePaths({
    global = false,
  }: { global?: boolean } = {}): ToolSkillSettablePaths {
    if (global) {
      return { relativeDirPath: GITLABDUO_GLOBAL_SKILLS_DIR };
    }
    return {
      relativeDirPath: GITLABDUO_SKILLS_DIR,
      importOnlySkillRoots: [GITLABDUO_LEGACY_SKILLS_DIR],
    };
  }

  static override isTargetedByRulesyncSkill(rulesyncSkill: RulesyncSkill): boolean {
    const targets = rulesyncSkill.getFrontmatter().targets;
    return targets.includes("*") || targets.includes("gitlabduo");
  }

  /**
   * The import-only project-root `skills/` directory is one many repositories
   * already use for unrelated content, so only a subdirectory holding a
   * `SKILL.md` is treated as a skill, in every root this target reads.
   */
  static async isDirOwned({
    outputRoot,
    relativeDirPath,
    dirName,
  }: {
    outputRoot: string;
    relativeDirPath: string;
    dirName: string;
  }): Promise<boolean> {
    return await fileExists(join(outputRoot, relativeDirPath, dirName, SKILL_FILE_NAME));
  }
}
